export const GLYPH = {};
for (const [k, v] of Object.entries(raw)) GLYPH[k] = v.split("/");

export const LEBAR_HURUF = 5, TINGGI_HURUF = 7, JARAK = 1;

/** Buang aksen dan ganti karakter khusus agar semua huruf ada di font. */
export function bersihkan(teks) {
  return String(teks).normalize("NFD").replace(/[̀-ͯ]/g, "")
    .replace(/[‐-―−]/g, "-").replace(/[×✕]/g, "x").replace(/[’‘`]/g, "'").replace(/[“”]/g, '"')
    .replace(/[₀₁₂₃₄₅₆₇₈₉]/g, (c) => String("₀₁₂₃₄₅₆₇₈₉".indexOf(c)))
    .replace(/[^\x20-\x7e]/g, "?");
}
export function ukurTeks(teks, skala = 1) {
  const t = bersihkan(teks); if (!t.length) return 0;
  return (t.length * (LEBAR_HURUF + JARAK) - JARAK) * skala;
}
/** Skala terbesar (<= maks) agar teks muat di lebar maksimum. */
export function skalaMuat(teks, lebarMaks, maks = 4) {
  for (let s = maks; s >= 1; s--) if (ukurTeks(teks, s) <= lebarMaks) return s;
  return 1;
}
/** Gambar teks pixel di ctx. rata: "kiri" | "tengah" | "kanan". Mengembalikan lebar yang terpakai. */
export function gambarTeks(ctx, teks, x, y, skala = 1, warna = "#fff", rata = "kiri") {
  const t = bersihkan(teks), w = ukurTeks(t, skala);
  let cx = rata === "tengah" ? x - Math.floor(w / 2) : rata === "kanan" ? x - w : x;
  ctx.fillStyle = warna;
  for (const ch of t) {
    const g = GLYPH[ch] || GLYPH["?"];
    for (let r = 0; r < TINGGI_HURUF; r++) for (let c = 0; c < LEBAR_HURUF; c++) if (g[r][c] === "#") ctx.fillRect(cx + c * skala, y + r * skala, skala, skala);
    cx += (LEBAR_HURUF + JARAK) * skala;
  }
  return w;
}
/** Rumus kimia dengan angka bawah (subscript) lebih kecil: pecah = [[simbol, jumlah], ...]. */
export function gambarRumus(ctx, pecah, x, y, skala = 2, warna = "#fff", rata = "kiri", warnaAngka = warna) {
  const sub = Math.max(1, skala - 1);
  const bagian = [];
  for (const [s, n] of pecah) { bagian.push([s, skala]); if (n > 1) bagian.push([String(n), sub]); }
  const total = bagian.reduce((a, [t, k]) => a + ukurTeks(t, k) + JARAK * k, 0) - JARAK * skala;
  let cx = rata === "tengah" ? x - Math.floor(total / 2) : rata === "kanan" ? x - total : x;
  for (const [t, k] of bagian) {
    const angka = k !== skala, dy = angka ? (TINGGI_HURUF * skala - TINGGI_HURUF * k) + k * 2 : 0;
    gambarTeks(ctx, t, cx, y + dy, k, angka ? warnaAngka : warna);
    cx += ukurTeks(t, k) + JARAK * k;
  }
  return total;
}
/** Pecah teks menjadi baris dengan maksimum karakter per baris. */
export function bungkus(teks, maksKar) {
  const kata = bersihkan(teks).split(/\s+/).filter(Boolean), baris = []; let cur = "";
  for (const k of kata) {
    if (!cur) cur = k;
    else if ((cur + " " + k).length <= maksKar) cur += " " + k;
    else { baris.push(cur); cur = k; }
  }
  if (cur) baris.push(cur);
  return baris;
}
